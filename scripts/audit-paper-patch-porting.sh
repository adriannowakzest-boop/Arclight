#!/usr/bin/env bash
set -euo pipefail

readonly PAPER_DIR="${PAPER_UPSTREAM_DIR:-build/paper-upstream-1.20.1}"
readonly OUTPUT="${PAPER_PATCH_AUDIT_OUTPUT:-build/paper-patch-porting-inventory.md}"
readonly ARCLIGHT_SOURCE="arclight-common/src/main/java"

if [[ ! -d "$PAPER_DIR/patches/server" || ! -d "$PAPER_DIR/patches/api" ]]; then
  echo "Pinned Paper patch directories not found under $PAPER_DIR. Run scripts/prepare-paper-upstream.sh first." >&2
  exit 1
fi
if [[ ! -d "$ARCLIGHT_SOURCE" ]]; then
  echo "Arclight Java source directory not found: $ARCLIGHT_SOURCE" >&2
  exit 1
fi

mkdir -p "$(dirname "$OUTPUT")"
{
  echo "# Paper 1.20.1 patch porting inventory"
  echo
  printf '%s\\n' '- Upstream commit: `773dd724469bae89d0c2075edc3d1ddc8d5b0b18`'
  printf '%s\\n' '- Generated by: `scripts/audit-paper-patch-porting.sh`'
  echo "- This report is an impact inventory, not proof that a patch is ported."
  echo
  echo "| Patch set | Patch | Impact | Arclight mixin matches | Changed source paths |"
  echo "|---|---|---:|---:|---:|"

  total=0
  for set in api server; do
    while IFS= read -r patch; do
      [[ -f "$patch" ]] || continue
      total=$((total + 1))
      relative="${patch#"$PAPER_DIR/"}"
      subject="$(sed -n 's/^Subject: \[PATCH\] //p' "$patch" | head -n 1)"
      mapfile -t paths < <(awk '/^diff --git a\// { sub(/^diff --git a\//, ""); sub(/ b\/.*$/, ""); print }' "$patch" | sort -u)
      source_count=0
      match_count=0
      risk="low"
      matches=()
      for path in "${paths[@]}"; do
        if [[ "$path" == *.java ]]; then
          source_count=$((source_count + 1))
          base="$(basename "$path" .java)"
          if [[ "$path" == *"/net/minecraft/"* || "$path" == *"/org/bukkit/craftbukkit/"* || "$base" =~ (Server|World|Chunk|Entity|Plugin|CraftServer|MinecraftServer) ]]; then
            risk="high"
          elif [[ "$risk" != "high" ]]; then
            risk="medium"
          fi
          while IFS= read -r match; do
            [[ -n "$match" ]] || continue
            match_count=$((match_count + 1))
            matches+=("${match#"$ARCLIGHT_SOURCE/"}")
          done < <(find "$ARCLIGHT_SOURCE" -type f -name "*${base}*Mixin.java" -print 2>/dev/null | sort -u)
        fi
      done
      match_text="—"
      if (( match_count > 0 )); then
        match_text="$match_count"
      fi
      path_text="—"
      if (( ${#paths[@]} > 0 )); then
        path_text="$(printf '%s, ' "${paths[@]}")"
        path_text="${path_text%, }"
        path_text="${path_text//|/\\|}"
      fi
      echo "| $set | [$(basename "$patch")] — ${subject:-no subject} | $risk | $match_text | $path_text |"
      if (( ${#matches[@]} > 0 )); then
        printf '  - Arclight candidates for %s: ' "$(basename "$patch")"
        printf '`%s` ' "${matches[@]}"
        echo
      fi
    done < <(find "$PAPER_DIR/patches/$set" -maxdepth 1 -type f -name '*.patch' -print | sort)
  done
  echo
  echo "Total top-level API/server patches inventoried: $total"
  if (( total == 0 )); then
    echo "No Paper patches were found." >&2
    exit 1
  fi
} > "$OUTPUT"

echo "Paper patch inventory written to $OUTPUT"
